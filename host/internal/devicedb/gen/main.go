// Command gen builds devices.tsv from a device-catalog CSV export.
//
// The input is any CSV whose header names a brand, a model name and a screen
// size column; a manufacturer column and a form-factor column are used when
// present. Columns are found by case-insensitive substring so a re-export
// with extra or reordered columns still works, and nothing beyond those five
// is ever read.
//
// Output is one line per distinct (brand, name, size): brand, model name,
// width and height, tab-separated, portrait, sorted — so a regenerate from
// the same export is byte-identical and a PR diff shows only real changes.
//
//	go generate ./internal/devicedb
package main

import (
	"bufio"
	"encoding/csv"
	"flag"
	"fmt"
	"io"
	"os"
	"sort"
	"strconv"
	"strings"
)

// Same bounds config.Validate applies to a resolution; anything outside them
// could never be selected anyway.
const (
	minAxis = 320
	maxAxis = 10000
)

type entry struct {
	brand  string
	name   string
	width  int
	height int
}

func main() {
	in := flag.String("in", "", "catalog CSV to read")
	out := flag.String("out", "devices.tsv", "TSV to write")
	flag.Parse()
	if *in == "" {
		fmt.Fprintln(os.Stderr, "gen: -in is required")
		os.Exit(2)
	}
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(inPath, outPath string) error {
	f, err := os.Open(inPath)
	if err != nil {
		return err
	}
	defer f.Close()

	entries, err := read(f)
	if err != nil {
		return err
	}
	sort.Slice(entries, func(i, j int) bool {
		a, b := entries[i], entries[j]
		if ab, bb := strings.ToLower(a.brand), strings.ToLower(b.brand); ab != bb {
			return ab < bb
		}
		if an, bn := strings.ToLower(a.name), strings.ToLower(b.name); an != bn {
			return an < bn
		}
		if a.width != b.width {
			return a.width < b.width
		}
		return a.height < b.height
	})

	w, err := os.Create(outPath)
	if err != nil {
		return err
	}
	bw := bufio.NewWriter(w)
	fmt.Fprintln(bw, "# brand\tmodel\twidth\theight — portrait pixels; generated by gen, do not edit")
	for _, e := range entries {
		fmt.Fprintf(bw, "%s\t%s\t%d\t%d\n", e.brand, e.name, e.width, e.height)
	}
	if err := bw.Flush(); err != nil {
		return err
	}
	if err := w.Close(); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "gen: wrote %d devices to %s\n", len(entries), outPath)
	return nil
}

// read parses the CSV into de-duplicated portrait entries. Rows are kept only
// for phones and tablets when the export says which is which; a row with
// several sizes (a foldable, or a phone with a resolution switch) becomes one
// entry per size.
func read(r io.Reader) ([]entry, error) {
	cr := csv.NewReader(r)
	cr.FieldsPerRecord = -1
	header, err := cr.Read()
	if err != nil {
		return nil, fmt.Errorf("reading header: %w", err)
	}
	header[0] = strings.TrimPrefix(header[0], "\ufeff")

	brandCol := findColumn(header, "brand")
	makerCol := findColumn(header, "manufacturer")
	nameCol := findColumn(header, "model name")
	if nameCol < 0 {
		nameCol = findColumn(header, "model")
	}
	formCol := findColumn(header, "form factor")
	sizeCol := findColumn(header, "screen size")
	if brandCol < 0 && makerCol < 0 {
		return nil, fmt.Errorf("no brand or manufacturer column in %q", header)
	}
	if nameCol < 0 || sizeCol < 0 {
		return nil, fmt.Errorf("need a model name and a screen size column in %q", header)
	}

	seen := make(map[string]bool)
	var entries []entry
	for {
		rec, err := cr.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		if formCol >= 0 {
			switch strings.ToLower(field(rec, formCol)) {
			case "phone", "tablet":
			default:
				continue
			}
		}
		brand := field(rec, makerCol)
		if brand == "" {
			brand = field(rec, brandCol)
		}
		name := clean(field(rec, nameCol))
		brand = clean(brand)
		if brand == "" || name == "" {
			continue
		}
		for _, size := range strings.Split(field(rec, sizeCol), ";") {
			width, height, ok := parseSize(size)
			if !ok {
				continue
			}
			key := strings.ToLower(brand) + "\x00" + name + "\x00" + strconv.Itoa(width) + "x" + strconv.Itoa(height)
			if seen[key] {
				continue
			}
			seen[key] = true
			entries = append(entries, entry{brand: brand, name: name, width: width, height: height})
		}
	}
	return entries, nil
}

func findColumn(header []string, want string) int {
	for i, h := range header {
		if strings.Contains(strings.ToLower(h), want) {
			return i
		}
	}
	return -1
}

func field(rec []string, col int) string {
	if col < 0 || col >= len(rec) {
		return ""
	}
	return strings.TrimSpace(rec[col])
}

// clean collapses whitespace and strips anything that would break a TSV line.
func clean(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// parseSize reads "WxH" and returns it portrait (short side first), which is
// how the picker presents every device; the orientation toggle flips it.
func parseSize(s string) (int, int, bool) {
	parts := strings.Split(strings.ToLower(strings.TrimSpace(s)), "x")
	if len(parts) != 2 {
		return 0, 0, false
	}
	a, err1 := strconv.Atoi(strings.TrimSpace(parts[0]))
	b, err2 := strconv.Atoi(strings.TrimSpace(parts[1]))
	if err1 != nil || err2 != nil {
		return 0, 0, false
	}
	if a > b {
		a, b = b, a
	}
	if a < minAxis || b > maxAxis {
		return 0, 0, false
	}
	return a, b, true
}
